-- one user can have only one profile
drop table if exists user_profile;
create table user_profile (
    user_id integer not null,
    first_name varchar(128) null,
    last_name varchar(128) null,
    screen_name varchar(128) null,
    birth_month integer null,
    birth_year integer null,
    gender varchar(16) null,
	height float4 null,
    weight integer null,
    phone varchar(64) null,
    is_active boolean default true,
	created_user integer null,
	created_date timestamp not null default current_timestamp,
	modified_date timestamp not null default current_timestamp,
    constraint pk_user_profile primary key (user_id),
    constraint uq_user_profile_name unique (first_name, last_name),
    constraint uq_user_profile_screen unique (screen_name),
    constraint uq_user_profile_phone unique (phone)
);


-- signup table before creating profile and this is temporary
drop table if exists user_signup;
create table user_signup(
    signup_id integer generated by default as identity,
    email varchar(128) not null,
    otp varchar(256) not null,
    expiry timestamp with time zone not null,
    created_date timestamp not null default current_timestamp,
    modified_date timestamp not null default current_timestamp,
    is_verified boolean default false,
    constraint pk_user_signup primary key (signup_id)
);

-- one user can have many addresses
drop table if exists user_address;
create table user_address(
	address_id integer generated by default as identity,
	user_id integer not null,
    street varchar(128) null,
    city varchar(128) not null,
    county varchar(128) null,
    state varchar(128) not null,
    zip_code varchar(128) null,
    country varchar(128) not null,
	from_month integer not null,
	from_year integer not null,
	created_date timestamp not null default current_timestamp,
	modified_date timestamp not null default current_timestamp,
    constraint pk_user_address primary key (address_id),
	constraint uq_user_address unique (user_id, from_month, from_year)
);

